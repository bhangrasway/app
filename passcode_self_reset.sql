-- ============================================================================
-- "FORGOT YOUR PASSCODE?" — RESET IT YOURSELF. Run once in the Supabase SQL
-- editor (Project -> SQL Editor -> New query -> paste -> Run). Safe to re-run.
--
-- Two options in member.html:
--   1. Reset it yourself: codice fiscale (the student's, or the parent's) +
--      one more answer, with a hint:
--        - students with a parent on file (kids): the parent's first name
--        - everyone else: the street of their address (without «Via»)
--      Then they choose a new 4-digit passcode straight away.
--   2. Send a request to the admin (request_passcode_reset_by_phone, as before).
--
-- 5 wrong tries in an hour lock the self-reset for that student (option 2
-- still works). Answers ignore capitals, accents, spaces and «Via/Piazza…».
-- ============================================================================

create table if not exists public.passcode_reset_attempts (
    id bigint generated by default as identity primary key,
    student_id bigint not null,
    success boolean not null default false,
    created_at timestamptz not null default now()
);
alter table public.passcode_reset_attempts enable row level security;
drop policy if exists "authenticated_all" on public.passcode_reset_attempts;
create policy "authenticated_all" on public.passcode_reset_attempts for all to authenticated using (true) with check (true);
revoke all on public.passcode_reset_attempts from anon;

-- lower case, no accents, letters and digits only
create or replace function public._norm_answer(p text)
returns text language sql immutable as $$
    select regexp_replace(
        translate(lower(coalesce(p, '')), 'àáâäãèéêëìíîïòóôöõùúûüçñ', 'aaaaaeeeeiiiiooooouuuucn'),
        '[^a-z0-9]', '', 'g');
$$;
-- the street without its type: "Via Fratelli Cervi" -> "fratellicervi"
create or replace function public._norm_street(p text)
returns text language sql immutable as $$
    select public._norm_answer(regexp_replace(lower(trim(coalesce(p, ''))),
        '^(via|viale|v\.le|piazza|p\.za|p\.zza|piazzale|p\.le|piazzetta|corso|c\.so|largo|vicolo|strada|str\.|localit[aà]|loc\.|frazione|fraz\.|contrada|c\.da|borgo|cascina|salita|traversa)\.?\s+', ''));
$$;
-- "Fratelli Cervi" -> "F******i C***i" (first and last letter of each word)
create or replace function public._mask_hint(p text)
returns text language plpgsql immutable as $$
declare
    w text;
    out text := '';
begin
    foreach w in array regexp_split_to_array(trim(coalesce(p, '')), '\s+') loop
        if w = '' then continue; end if;
        out := out || case when length(w) <= 2 then left(w, 1) || '*'
                           else left(w, 1) || repeat('*', length(w) - 2) || right(w, 1) end || ' ';
    end loop;
    return trim(out);
end;
$$;

-- Which question this student gets, and its hint.
-- Returns { status: 'ok'|'bad_phone', kind: 'parent'|'street'|'none', hint }
create or replace function public.get_passcode_reset_question_by_phone(p_student_id bigint, p_phone text)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    s record;
    v_street text;
begin
    if not public._phone_matches_student(p_student_id, p_phone) then
        return jsonb_build_object('status', 'bad_phone');
    end if;
    select * into s from public.students where id = p_student_id;
    if coalesce(trim(s.parent_nome), '') <> '' then
        return jsonb_build_object('status', 'ok', 'kind', 'parent', 'hint', public._mask_hint(s.parent_nome));
    end if;
    v_street := regexp_replace(trim(coalesce(s.addr_via, '')),
        '^(via|viale|piazza|piazzale|corso|largo|vicolo|strada|localit[aà]|frazione|contrada|borgo)\.?\s+', '', 'i');
    if v_street <> '' then
        return jsonb_build_object('status', 'ok', 'kind', 'street', 'hint', public._mask_hint(v_street));
    end if;
    return jsonb_build_object('status', 'ok', 'kind', 'none');
end;
$$;

-- Checks codice fiscale + answer, then sets the new passcode.
-- Returns 'ok' | 'bad_phone' | 'invalid_format' | 'no_question' | 'too_many' | 'wrong'
create or replace function public.reset_passcode_self_by_phone(
    p_student_id bigint, p_phone text, p_cf text, p_answer text, p_new_passcode text)
returns text
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
    s record;
    v jsonb;
    v_cf text := upper(regexp_replace(coalesce(p_cf, ''), '\s', '', 'g'));
    v_cf_ok boolean;
    v_answer_ok boolean;
begin
    if not public._phone_matches_student(p_student_id, p_phone) then return 'bad_phone'; end if;
    if p_new_passcode !~ '^\d{4}$' then return 'invalid_format'; end if;
    if (select count(*) from public.passcode_reset_attempts
        where student_id = p_student_id and not success and created_at > now() - interval '1 hour') >= 5 then
        return 'too_many';
    end if;

    select * into s from public.students where id = p_student_id;
    v := to_jsonb(s);
    v_cf_ok := length(v_cf) = 16 and (
        v_cf = upper(coalesce(v->>'codicefiscale', v->>'codice_fiscale', v->>'codiceFiscale', ''))
        or v_cf = upper(coalesce(s.parent_codice_fiscale, '')));

    if coalesce(trim(s.parent_nome), '') <> '' then
        v_answer_ok := public._norm_answer(p_answer) <> '' and public._norm_answer(p_answer) = public._norm_answer(s.parent_nome);
    elsif coalesce(trim(s.addr_via), '') <> '' then
        v_answer_ok := public._norm_street(p_answer) <> '' and public._norm_street(p_answer) = public._norm_street(s.addr_via);
    else
        return 'no_question';
    end if;

    if not (v_cf_ok and v_answer_ok) then
        insert into public.passcode_reset_attempts (student_id, success) values (p_student_id, false);
        return 'wrong';
    end if;

    update public.students
    set passcode_hash = crypt(p_new_passcode, gen_salt('bf')),
        passcode_changed_at = now()
    where id = p_student_id;
    insert into public.passcode_reset_attempts (student_id, success) values (p_student_id, true);
    return 'ok';
end;
$$;

revoke all on function public.get_passcode_reset_question_by_phone(bigint, text) from public;
revoke all on function public.reset_passcode_self_by_phone(bigint, text, text, text, text) from public;
grant execute on function public.get_passcode_reset_question_by_phone(bigint, text) to anon, authenticated;
grant execute on function public.reset_passcode_self_by_phone(bigint, text, text, text, text) to anon, authenticated;
