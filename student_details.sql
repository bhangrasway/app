-- ============================================================================
-- STUDENT DETAILS — run once in the Supabase SQL editor
-- (Project -> SQL Editor -> New query -> paste -> Run).
--
-- Clean, separate anagrafica fields — the foundation for correct fatture
-- (a wrong/unsplit name, a free-text provincia like "bg", or a mistyped
-- codice fiscale is exactly what gets an e-invoice "scartata").
--
--  1. students: nome/cognome, parent nome/cognome/codice fiscale, and the
--     address split into its own columns (provincia always a 2-letter
--     sigla, picked from the official comuni list in admin.html/member.html).
--     The old single columns (name, parentname, address) stay and are kept
--     in sync by admin.html on every save, so nothing that reads them breaks.
--  2. student_detail_requests: a student's own corrections from the member
--     portal, waiting for admin approval (old -> new per field).
--  3. Two member RPCs (phone + passcode verified, same trust model as
--     request_batch_change_by_phone): read my details / request a change.
--     A correction can include a new close-up photo (photo_path, already
--     uploaded to the student-photos bucket); it only becomes the student's
--     photo when the admin approves the request.
--
-- Safe to re-run (everything is "if not exists" / "create or replace").
-- ============================================================================

-- ===== 1. New columns =====
alter table public.students add column if not exists nome text;
alter table public.students add column if not exists cognome text;
alter table public.students add column if not exists parent_nome text;
alter table public.students add column if not exists parent_cognome text;
alter table public.students add column if not exists parent_codice_fiscale text;
alter table public.students add column if not exists addr_via text;
alter table public.students add column if not exists addr_civico text;
alter table public.students add column if not exists addr_cap text;
alter table public.students add column if not exists addr_comune text;
alter table public.students add column if not exists addr_provincia text;

-- ===== 2. Correction requests from students =====
-- changes: { "<field>": { "old": "...", "new": "..." }, ... } — only the
-- fields the student actually changed. Admin-only table; member.html never
-- touches it directly, only through request_details_change_by_phone.
create table if not exists public.student_detail_requests (
    id bigint generated by default as identity primary key,
    student_id bigint not null,
    student_name text,
    changes jsonb not null,
    status text not null default 'pending', -- 'pending' | 'approved' | 'dismissed'
    requested_at timestamptz not null default now(),
    resolved_at timestamptz
);

alter table public.student_detail_requests enable row level security;
drop policy if exists "authenticated_all" on public.student_detail_requests;
create policy "authenticated_all" on public.student_detail_requests
    for all to authenticated using (true) with check (true);
revoke all on public.student_detail_requests from anon;

-- ===== 3a. RPC: read my own details =====
-- to_jsonb(s) so the codice fiscale column is found whatever its casing
-- (codicefiscale / codice_fiscale / codiceFiscale — the live schema's exact
-- name was never confirmed, admin.html already probes all three).
create or replace function public.get_my_details_by_phone(
    p_student_id bigint,
    p_phone text,
    p_passcode text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v jsonb;
begin
    if not public._phone_matches_student(p_student_id, p_phone) then
        return null;
    end if;
    if not public._passcode_matches_student(p_student_id, p_passcode) then
        return null;
    end if;

    select to_jsonb(s) into v from public.students s where s.id = p_student_id;
    if v is null then
        return null;
    end if;

    return jsonb_build_object(
        'name', v->>'name',
        'parentname', coalesce(v->>'parentname', v->>'parent_name', v->>'parentName'),
        'address', v->>'address',
        'nome', v->>'nome',
        'cognome', v->>'cognome',
        'codice_fiscale', coalesce(v->>'codicefiscale', v->>'codice_fiscale', v->>'codiceFiscale'),
        'parent_nome', v->>'parent_nome',
        'parent_cognome', v->>'parent_cognome',
        'parent_codice_fiscale', v->>'parent_codice_fiscale',
        'addr_via', v->>'addr_via',
        'addr_civico', v->>'addr_civico',
        'addr_cap', v->>'addr_cap',
        'addr_comune', v->>'addr_comune',
        'addr_provincia', v->>'addr_provincia',
        'photo_path', v->>'photo_path',
        'has_pending_request', exists (
            select 1 from public.student_detail_requests r
            where r.student_id = p_student_id and r.status = 'pending'
        )
    );
end;
$$;

grant execute on function public.get_my_details_by_phone(bigint, text, text) to anon;

-- ===== 3b. RPC: send a correction for admin approval =====
-- Returns: 'sent' | 'bad_phone' | 'bad_passcode' | 'empty' | 'bad_field'
-- Only whitelisted fields are accepted; a newer request replaces an older
-- pending one instead of stacking duplicates (same as batch requests).
create or replace function public.request_details_change_by_phone(
    p_student_id bigint,
    p_phone text,
    p_changes jsonb,
    p_passcode text default null
)
returns text
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_name text;
    v_key text;
    v_allowed text[] := array[
        'nome', 'cognome', 'codice_fiscale',
        'parent_nome', 'parent_cognome', 'parent_codice_fiscale',
        'addr_via', 'addr_civico', 'addr_cap', 'addr_comune', 'addr_provincia',
        'photo_path'
    ];
begin
    if not public._phone_matches_student(p_student_id, p_phone) then
        return 'bad_phone';
    end if;
    if not public._passcode_matches_student(p_student_id, p_passcode) then
        return 'bad_passcode';
    end if;
    if p_changes is null or jsonb_typeof(p_changes) <> 'object' or p_changes = '{}'::jsonb then
        return 'empty';
    end if;
    for v_key in select jsonb_object_keys(p_changes) loop
        if not (v_key = any (v_allowed)) then
            return 'bad_field';
        end if;
        if length(coalesce(p_changes->v_key->>'new', '')) > 120 then
            return 'bad_field';
        end if;
    end loop;

    select name into v_name from public.students where id = p_student_id;

    update public.student_detail_requests
    set status = 'dismissed', resolved_at = now()
    where student_id = p_student_id and status = 'pending';

    insert into public.student_detail_requests (student_id, student_name, changes)
    values (p_student_id, v_name, p_changes);

    return 'sent';
end;
$$;

grant execute on function public.request_details_change_by_phone(bigint, text, jsonb, text) to anon;
