-- ============================================================================
-- ADMIN NOTIFICATIONS (web push) — run once in the Supabase SQL editor
-- (Project -> SQL Editor -> New query -> paste -> Run), after
-- push_notifications.sql. Safe to re-run.
--
-- The bell in the admin header turns on notifications on that phone/computer
-- (row in admin_push_subscriptions). When a student sends a request, a trigger
-- calls the Edge Function "send-push" with { to: 'admin' }, which notifies
-- every admin device.
--
-- Requests that notify: passcode reset, manual check-in, batch change,
-- change of personal details, medical certificate upload.
--
-- The trigger proves itself to the function with a secret kept in Supabase
-- Vault (name 'push_trigger_secret'), never in this public file: it is set
-- once with a separate private snippet, and the same value is the Edge
-- Function secret PUSH_TRIGGER_SECRET. Without it the triggers do nothing.
--
-- The older ntfy.sh triggers (ntfy_admin_notifications.sql), if installed,
-- keep working alongside; drop them whenever you no longer use the ntfy app.
-- ============================================================================

create extension if not exists pg_net with schema extensions;

create table if not exists public.admin_push_subscriptions (
    id bigint generated by default as identity primary key,
    endpoint text not null unique,
    p256dh text not null,
    auth text not null,
    user_agent text,
    created_at timestamptz not null default now()
);
alter table public.admin_push_subscriptions enable row level security;
drop policy if exists "authenticated_all" on public.admin_push_subscriptions;
create policy "authenticated_all" on public.admin_push_subscriptions for all to authenticated using (true) with check (true);
revoke all on public.admin_push_subscriptions from anon;

create or replace function public.notify_admin_push()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_secret text;
    v_name   text := coalesce(new.student_name, 'A student');
    v_title  text;
    v_body   text;
begin
    select decrypted_secret into v_secret from vault.decrypted_secrets where name = 'push_trigger_secret' limit 1;
    if v_secret is null then
        return new; -- not set up yet
    end if;

    if TG_TABLE_NAME = 'passcode_reset_requests' then
        v_title := 'Passcode reset requested';
        v_body  := v_name || ' requested a passcode reset.';
    elsif TG_TABLE_NAME = 'checkin_requests' then
        v_title := 'Manual check-in requested';
        v_body  := v_name || ' requested a manual check-in'
                   || case when nullif(trim(new.reason), '') is not null then ' (' || new.reason || ')' else '' end || '.';
    elsif TG_TABLE_NAME = 'batch_change_requests' then
        v_title := 'Batch change requested';
        v_body  := v_name || ' asked to move to ' || coalesce(new.requested_batch, 'a new batch') || '.';
    elsif TG_TABLE_NAME = 'student_detail_requests' then
        v_title := 'Details to approve';
        v_body  := v_name || ' sent corrections to their personal details.';
    elsif TG_TABLE_NAME = 'medical_certificate_submissions' then
        v_title := 'Medical certificate uploaded';
        v_body  := v_name || ' uploaded a medical certificate to check.';
    else
        v_title := 'Admin panel';
        v_body  := 'New pending request.';
    end if;

    perform net.http_post(
        url     := 'https://geeqcyfnkgamcjclulay.supabase.co/functions/v1/send-push',
        body    := jsonb_build_object('to', 'admin', 'title', v_title, 'body', v_body, 'url', 'admin.html'),
        headers := jsonb_build_object(
            'Content-Type', 'application/json',
            -- public anon key (also in admin.html/member.html): only gets past
            -- the function gateway; the real check is x-push-secret
            'Authorization', 'Bearer eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZSIsInJlZiI6ImdlZXFjeWZua2dhbWNqY2x1bGF5Iiwicm9sZSI6ImFub24iLCJpYXQiOjE3ODIwNDYyNjMsImV4cCI6MjA5NzYyMjI2M30.FPEQGtuDMxWK8GnPNQfh88ubXlQ2EIkV7X6FZN_TQpo',
            'x-push-secret', v_secret
        )
    );
    return new;
exception when others then
    return new; -- a notification problem must never block the student's request
end;
$$;

revoke all on function public.notify_admin_push() from public, anon, authenticated;

drop trigger if exists trg_admin_push_passcode_reset on public.passcode_reset_requests;
create trigger trg_admin_push_passcode_reset after insert on public.passcode_reset_requests
