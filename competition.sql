-- ===== Member: what is open, am I in, which team ===========================
-- The "current" event is the newest one that is not finished.
-- Returns {status:'bad_phone'|'bad_passcode'|'none'|'ok', event, entry, team, teammates}
create or replace function public.get_my_competition_by_phone(
    p_student_id bigint,
    p_phone text,
    p_passcode text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_event public.comp_events;
    v_entry public.comp_entries;
    v_team  public.comp_teams;
begin
    if not public._phone_matches_student(p_student_id, p_phone) then
        return jsonb_build_object('status', 'bad_phone');
    end if;
    if not public._passcode_matches_student(p_student_id, p_passcode) then
        return jsonb_build_object('status', 'bad_passcode');
    end if;

    select * into v_event from public.comp_events
    where status <> 'finished' order by created_at desc limit 1;
    if not found then
        return jsonb_build_object('status', 'none');
    end if;

    select * into v_entry from public.comp_entries
    where event_id = v_event.id and student_id = p_student_id;
    if found and v_entry.team_id is not null and v_event.status <> 'registration' then
        select * into v_team from public.comp_teams where id = v_entry.team_id;
    end if;

    return jsonb_build_object(
        'status', 'ok',
        'event', jsonb_build_object(
            'id', v_event.id, 'title', v_event.title, 'status', v_event.status,
            'reg_close', v_event.reg_close, 'fee', v_event.fee,
            'can_register', v_event.status = 'registration'
                and (v_event.reg_close is null or current_date <= v_event.reg_close)),
        'entry', case when v_entry.id is null or v_entry.withdrawn then null else jsonb_build_object(
            'kind', v_entry.kind, 'category', v_entry.category,
            'fee_charged', v_entry.fee_tx_id is not null) end,
        -- Team + teammates' first names only after the lock, never before.
        'team', case when v_team.id is null or v_entry.withdrawn then null else jsonb_build_object(
            'name', v_team.name, 'category', v_team.category,
            'teammates', coalesce((
                select jsonb_agg(split_part(trim(s.name), ' ', 1) order by s.name)
                from public.comp_entries e join public.students s on s.id = e.student_id
                where e.team_id = v_team.id and not e.withdrawn and e.student_id <> p_student_id
            ), '[]'::jsonb)) end
    );
end;
$$;
grant execute on function public.get_my_competition_by_phone(bigint, text, text) to anon;

-- ===== Member: register (or change compete <-> kids show) ==================
-- Returns {status:'ok'|'closed'|'bad_kind'|'bad_phone'|'bad_passcode'|'none'}
create or replace function public.register_competition_by_phone(
    p_student_id bigint,
    p_phone text,
    p_passcode text,
    p_kind text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_event public.comp_events;
begin
    if not public._phone_matches_student(p_student_id, p_phone) then
        return jsonb_build_object('status', 'bad_phone');
    end if;
    if not public._passcode_matches_student(p_student_id, p_passcode) then
        return jsonb_build_object('status', 'bad_passcode');
    end if;
    if p_kind not in ('compete', 'kids_show') then
        return jsonb_build_object('status', 'bad_kind');
    end if;

    select * into v_event from public.comp_events
    where status <> 'finished' order by created_at desc limit 1;
    if not found then
        return jsonb_build_object('status', 'none');
    end if;
    if v_event.status <> 'registration' or (v_event.reg_close is not null and current_date > v_event.reg_close) then
        return jsonb_build_object('status', 'closed');
    end if;

    insert into public.comp_entries (event_id, student_id, kind)
    values (v_event.id, p_student_id, p_kind)
    on conflict (event_id, student_id)
    do update set kind = excluded.kind, withdrawn = false;

    return jsonb_build_object('status', 'ok');
end;
$$;
grant execute on function public.register_competition_by_phone(bigint, text, text, text) to anon;

-- ===== Member: withdraw (only before the lock) =============================
create or replace function public.withdraw_competition_by_phone(
    p_student_id bigint,
    p_phone text,
    p_passcode text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_event public.comp_events;
begin
    if not public._phone_matches_student(p_student_id, p_phone) then
        return jsonb_build_object('status', 'bad_phone');
    end if;
    if not public._passcode_matches_student(p_student_id, p_passcode) then
        return jsonb_build_object('status', 'bad_passcode');
    end if;

    select * into v_event from public.comp_events
    where status <> 'finished' order by created_at desc limit 1;
    if not found then
        return jsonb_build_object('status', 'none');
    end if;
    if v_event.status <> 'registration' or (v_event.reg_close is not null and current_date > v_event.reg_close) then
        return jsonb_build_object('status', 'closed');
    end if;

    update public.comp_entries set withdrawn = true
    where event_id = v_event.id and student_id = p_student_id;
    return jsonb_build_object('status', 'ok');
end;
$$;
grant execute on function public.withdraw_competition_by_phone(bigint, text, text) to anon;

