-- ============================================================================
-- COMPETITION (phase 1: registration + teams) — run once in the Supabase SQL
-- editor (Project -> SQL Editor -> New query -> paste -> Run). Safe to re-run.
--
--   * comp_events   — one row per competition (title, status, close date, fee).
--   * comp_teams    — teams per category; fixed = a location team that stays as is.
--   * comp_entries  — who registered: compete or kids_show, category, team, fee row.
--
-- Admin (the studio login) reads/writes everything (admin_only policy, same as
-- the rest of the app). Members never read these tables directly: they go
-- through the phone/passcode-verified RPCs at the bottom.
-- ============================================================================

create table if not exists public.comp_events (
    id          bigint generated by default as identity primary key,
    title       text not null,
    status      text not null default 'registration'
                    check (status in ('registration', 'locked', 'live', 'finished')),
    reg_close   date,                      -- last day members can register / withdraw
    fee         numeric not null default 20,
    settings    jsonb not null default '{}'::jsonb,
    created_at  timestamptz not null default now()
);

create table if not exists public.comp_teams (
    id          bigint generated by default as identity primary key,
    event_id    bigint not null references public.comp_events(id) on delete cascade,
    category    text not null check (category in ('A', 'B')),
    name        text not null,
    fixed       boolean not null default false,
    location_id bigint,                    -- set for the fixed location teams
    sort_order  integer not null default 0,
    unique (event_id, name)
);

create table if not exists public.comp_entries (
    id          bigint generated by default as identity primary key,
    event_id    bigint not null references public.comp_events(id) on delete cascade,
    student_id  bigint not null references public.students(id),
    kind        text not null default 'compete' check (kind in ('compete', 'kids_show')),
    category    text check (category in ('A', 'B')),
    team_id     bigint references public.comp_teams(id) on delete set null,
    fee_tx_id   bigint,                    -- the v2_credit_transactions row charged at lock
    withdrawn   boolean not null default false,
    created_at  timestamptz not null default now(),
    unique (event_id, student_id)
);

create index if not exists comp_entries_event_idx on public.comp_entries(event_id);
create index if not exists comp_teams_event_idx on public.comp_teams(event_id);

alter table public.comp_events enable row level security;
alter table public.comp_teams enable row level security;
alter table public.comp_entries enable row level security;

