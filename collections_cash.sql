-- COLLECTIONS / CASH REGISTER — run once in the Supabase SQL editor
-- (Project -> SQL Editor -> New query -> paste -> Run). Safe to re-run.
--
--  * expenses.payment_method: 'cash' | 'bank'. A cash expense lowers «cash
--    on hand», a bank one lowers the bank figure in Income & Expense →
--    Collections. Old rows stay empty until set («Fill missing methods»).
--  * cash_deposits: cash taken to the bank (date, amount, optional ricevuta
--    in the tax-pdfs bucket). Admin only, like every other money table.
-- ============================================================================

alter table public.expenses add column if not exists payment_method text;
alter table public.expenses drop constraint if exists expenses_payment_method_check;
alter table public.expenses add constraint expenses_payment_method_check
    check (payment_method is null or payment_method in ('cash', 'bank'));

create table if not exists public.cash_deposits (
    id bigint generated by default as identity primary key,
    data date not null,
    importo numeric not null check (importo > 0),
    receipt_path text,
    note text,
    created_at timestamptz not null default now(),
    deleted_at timestamptz
);

alter table public.cash_deposits enable row level security;
drop policy if exists "admin_only" on public.cash_deposits;
create policy "admin_only" on public.cash_deposits
    for all to authenticated
    using (lower(auth.jwt() ->> 'email') = 'bhangrasway@gmail.com')
    with check (lower(auth.jwt() ->> 'email') = 'bhangrasway@gmail.com');
revoke all on public.cash_deposits from anon;
