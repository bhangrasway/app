-- TASSE — run once in the Supabase SQL editor (after fatture_xml.sql).
-- (Project -> SQL Editor -> New query -> paste -> Run). Safe to re-run.
--
-- The "Tasse" tab in admin.html (tasse.js): forfettario calculator, deadlines,
-- F24 lines ready to copy, credits and the record of every F24 sent.
-- Admin-only (same RLS as fatture). The actual filing/paying is done by the
-- user on the AdE site (Redditi / F24 web) or home banking.
--
--  tax_settings  one row: rate 5% start-up + years, coefficient, INPS rate/sede
--  tax_years     per tax year: the OFFICIAL figures from the declaration
--                (when present they win over the app's own calculation)
--  tax_credits   credits usable in F24 (e.g. IRPEF from the declaration's RX)
--  tax_f24       every F24 sent/paid, with its lines (debits and credits used)
-- ============================================================================

create table if not exists public.tax_settings (
    id int primary key default 1 check (id = 1),
    aliquota_agevolata numeric not null default 5,
    aliquota_ordinaria numeric not null default 15,
    anno_inizio int not null default 2025,
    anni_agevolati int not null default 5,
    coefficiente numeric not null default 78,
    inps_aliquota numeric not null default 26.07,
    inps_sede text,
    interesse_mensile numeric not null default 0.33,
    updated_at timestamptz not null default now()
);
insert into public.tax_settings (id) values (1) on conflict (id) do nothing;

create table if not exists public.tax_years (
    anno int primary key,
    ricavi numeric,
    reddito numeric,
    imposta numeric,
    inps numeric,
    acconto1_imposta numeric,
    acconto2_imposta numeric,
    acconto1_inps numeric,
    acconto2_inps numeric,
    dichiarazione_protocollo text,
    dichiarazione_data date,
    dichiarazione_pdf_path text,        -- the declaration PDF, stored in tax-pdfs
    note text,
    updated_at timestamptz not null default now()
);

-- (for databases created before this column existed)
alter table public.tax_years add column if not exists dichiarazione_pdf_path text;

create table if not exists public.tax_credits (
    id bigint generated by default as identity primary key,
    origine text not null,              -- e.g. 'IRPEF a credito — Redditi 2026 (RX1)'
    codice_tributo text not null,       -- e.g. '4001'
    anno_riferimento int not null,      -- e.g. 2025
    importo numeric not null,
    note text,
    created_at timestamptz not null default now(),
    deleted_at timestamptz
);

create table if not exists public.tax_f24 (
    id bigint generated by default as identity primary key,
    data date not null,
    scadenza text,                      -- e.g. '2026-06' / '2026-11' (which deadline it settles)
    descrizione text,
    -- [{ sezione: 'ERARIO'|'INPS', codice, anno, periodo, tipo, debito, credito, credit_id }]
    righe jsonb not null default '[]'::jsonb,
    totale numeric not null default 0,
    receipt_path text,
    created_at timestamptz not null default now(),
    deleted_at timestamptz
);

alter table public.tax_settings enable row level security;
alter table public.tax_years   enable row level security;
alter table public.tax_credits enable row level security;
alter table public.tax_f24     enable row level security;

drop policy if exists "authenticated_all" on public.tax_settings;
create policy "authenticated_all" on public.tax_settings for all to authenticated using (true) with check (true);
drop policy if exists "authenticated_all" on public.tax_years;
create policy "authenticated_all" on public.tax_years for all to authenticated using (true) with check (true);
drop policy if exists "authenticated_all" on public.tax_credits;
create policy "authenticated_all" on public.tax_credits for all to authenticated using (true) with check (true);
drop policy if exists "authenticated_all" on public.tax_f24;
create policy "authenticated_all" on public.tax_f24 for all to authenticated using (true) with check (true);

revoke all on public.tax_settings from anon;
revoke all on public.tax_years   from anon;
revoke all on public.tax_credits from anon;
revoke all on public.tax_f24     from anon;
