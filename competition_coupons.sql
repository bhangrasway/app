-- ============================================================================
-- COMPETITION: free invitation coupons for parents / guests — run once in the
-- Supabase SQL editor, AFTER competition_rules2.sql. Safe to re-run.
--
-- A student who takes part (solo, group or extra activity) can invite up to
-- 5 guests from the member app: one coupon per guest, with the guest's name and
-- a 6-character code. A coupon is a FREE entry. At the door the Door screen
-- checks the code (staff PIN) and marks it used, once.
--   comp_coupons                   the coupons (admin reads them)
--   get_my_coupons_by_phone        the student's own list
--   add_my_coupon_by_phone         create one (max 5)
--   delete_my_coupon_by_phone      remove an unused one
--   comp_door_coupon               Door: check / let in
--   comp_live.door_coupons         how many guests came in with a coupon
-- ============================================================================

create table if not exists public.comp_coupons (
    id          bigint generated by default as identity primary key,
    event_id    bigint not null references public.comp_events(id) on delete cascade,
    student_id  bigint not null references public.students(id),
    guest_name  text not null,
    code        text not null unique,
    used_at     timestamptz,
    created_at  timestamptz not null default now()
);
create index if not exists comp_coupons_student_idx on public.comp_coupons(event_id, student_id);

alter table public.comp_coupons enable row level security;
drop policy if exists "admin_only" on public.comp_coupons;
create policy "admin_only" on public.comp_coupons for all to authenticated
    using (lower(auth.jwt() ->> 'email') = 'bhangrasway@gmail.com')
    with check (lower(auth.jwt() ->> 'email') = 'bhangrasway@gmail.com');

alter table public.comp_live add column if not exists door_coupons integer not null default 0;

-- Codes without look-alike characters (no 0/O, 1/I)
create or replace function public._comp_new_code()
returns text
language plpgsql
as $$
declare
    chars text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
    c text;
    i int;
begin
    loop
        c := '';
        for i in 1..6 loop
            c := c || substr(chars, 1 + floor(random() * 32)::int, 1);
        end loop;
        exit when not exists (select 1 from public.comp_coupons where code = c);
    end loop;
    return c;
end;
$$;
revoke execute on function public._comp_new_code() from public, anon;

-- Does this student take part (so they may invite)?
create or replace function public._comp_student_takes_part(p_event_id bigint, p_student_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
    select exists (select 1 from public.comp_entries
                   where event_id = p_event_id and student_id = p_student_id and not withdrawn
                     and (do_solo or do_group or do_activity));
$$;
revoke execute on function public._comp_student_takes_part(bigint, bigint) from public, anon;

-- {status:'ok', eligible, max, coupons:[{id, guest_name, code, used}]}
create or replace function public.get_my_coupons_by_phone(p_student_id bigint, p_phone text, p_passcode text default null)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_event public.comp_events;
begin
    if not public._phone_matches_student(p_student_id, p_phone) then
        return jsonb_build_object('status', 'bad_phone');
    end if;
    if not public._passcode_matches_student(p_student_id, p_passcode) then
        return jsonb_build_object('status', 'bad_passcode');
    end if;
    v_event := public._comp_current_event();
    if v_event.id is null then
        return jsonb_build_object('status', 'none');
    end if;
    return jsonb_build_object(
        'status', 'ok', 'max', 5,
        'eligible', public._comp_student_takes_part(v_event.id, p_student_id),
        'coupons', coalesce((select jsonb_agg(jsonb_build_object('id', c.id, 'guest_name', c.guest_name, 'code', c.code, 'used', c.used_at is not null) order by c.id)
                             from public.comp_coupons c where c.event_id = v_event.id and c.student_id = p_student_id), '[]'::jsonb));
end;
$$;
grant execute on function public.get_my_coupons_by_phone(bigint, text, text) to anon;

-- {status:'ok'|'full'|'not_eligible'|'bad_name'|'none'|...}
create or replace function public.add_my_coupon_by_phone(p_student_id bigint, p_phone text, p_passcode text, p_guest_name text)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_event public.comp_events;
    v_name text := trim(coalesce(p_guest_name, ''));
begin
    if not public._phone_matches_student(p_student_id, p_phone) then
        return jsonb_build_object('status', 'bad_phone');
    end if;
    if not public._passcode_matches_student(p_student_id, p_passcode) then
        return jsonb_build_object('status', 'bad_passcode');
    end if;
    v_event := public._comp_current_event();
    if v_event.id is null then
        return jsonb_build_object('status', 'none');
    end if;
    if length(v_name) < 2 or length(v_name) > 40 then
        return jsonb_build_object('status', 'bad_name');
    end if;
    if not public._comp_student_takes_part(v_event.id, p_student_id) then
        return jsonb_build_object('status', 'not_eligible');
    end if;
    if (select count(*) from public.comp_coupons where event_id = v_event.id and student_id = p_student_id) >= 5 then
        return jsonb_build_object('status', 'full');
    end if;
    insert into public.comp_coupons (event_id, student_id, guest_name, code)
    values (v_event.id, p_student_id, v_name, public._comp_new_code());
    return jsonb_build_object('status', 'ok');
end;
$$;
grant execute on function public.add_my_coupon_by_phone(bigint, text, text, text) to anon;

-- Only an unused coupon of the student's own can be removed.
create or replace function public.delete_my_coupon_by_phone(p_student_id bigint, p_phone text, p_passcode text, p_coupon_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
    if not public._phone_matches_student(p_student_id, p_phone) then
        return jsonb_build_object('status', 'bad_phone');
    end if;
    if not public._passcode_matches_student(p_student_id, p_passcode) then
        return jsonb_build_object('status', 'bad_passcode');
    end if;
    delete from public.comp_coupons where id = p_coupon_id and student_id = p_student_id and used_at is null;
    return jsonb_build_object('status', 'ok');
end;
$$;
grant execute on function public.delete_my_coupon_by_phone(bigint, text, text, bigint) to anon;

-- Door screen (staff PIN, with the wrong-PIN lockout): check a code, and optionally let the guest in.
-- {status:'ok'|'used'|'not_found'|'bad_pin'|'too_many', guest, student, used_at}
create or replace function public.comp_door_coupon(p_pin text, p_code text, p_use boolean default false)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_event public.comp_events;
    v_gate text;
    v_c public.comp_coupons;
    v_student text;
begin
    v_event := public._comp_current_event();
    if v_event.id is null then
        return jsonb_build_object('status', 'bad_pin');
    end if;
    v_gate := public._comp_pin_gate(v_event.id, 'staff', p_pin);
    if v_gate <> 'ok' then
        return jsonb_build_object('status', v_gate);
    end if;
    select * into v_c from public.comp_coupons where event_id = v_event.id and code = upper(trim(coalesce(p_code, '')));
    if not found then
        return jsonb_build_object('status', 'not_found');
    end if;
    select name into v_student from public.students where id = v_c.student_id;
    if v_c.used_at is not null then
        return jsonb_build_object('status', 'used', 'guest', v_c.guest_name, 'student', v_student, 'used_at', v_c.used_at);
    end if;
    if coalesce(p_use, false) then
        update public.comp_coupons set used_at = now() where id = v_c.id;
        insert into public.comp_live (event_id) values (v_event.id) on conflict (event_id) do nothing;
        update public.comp_live set door_coupons = door_coupons + 1, updated_at = now() where event_id = v_event.id;
        return jsonb_build_object('status', 'ok', 'let_in', true, 'guest', v_c.guest_name, 'student', v_student);
    end if;
    return jsonb_build_object('status', 'ok', 'let_in', false, 'guest', v_c.guest_name, 'student', v_student);
end;
$$;
grant execute on function public.comp_door_coupon(text, text, boolean) to anon;

-- ===== Studio students come in free (coach, 2026-11-17) =====
-- The Door screen gets a third counter, "students": everyone who is a student of the
-- studio walks in free, whether they take part or not. It replaces comp_door_count
-- from competition_security.sql (same wrong-PIN lockout), adding kind 'student'.
alter table public.comp_live add column if not exists door_students integer not null default 0;

create or replace function public.comp_door_count(p_pin text, p_kind text, p_delta integer)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_event public.comp_events;
    v_live  public.comp_live;
    v_gate  text;
begin
    v_event := public._comp_current_event();
    if v_event.id is null then
        return jsonb_build_object('status', 'bad_pin');
    end if;
    v_gate := public._comp_pin_gate(v_event.id, 'staff', p_pin);
    if v_gate <> 'ok' then
        return jsonb_build_object('status', v_gate);
    end if;
    if p_kind not in ('cash', 'free', 'student') or p_delta not in (-1, 1) then
        return jsonb_build_object('status', 'bad_kind');
    end if;
    insert into public.comp_live (event_id) values (v_event.id) on conflict (event_id) do nothing;
    update public.comp_live
    set door_cash = greatest(0, door_cash + case when p_kind = 'cash' then p_delta else 0 end),
        door_free = greatest(0, door_free + case when p_kind = 'free' then p_delta else 0 end),
        door_students = greatest(0, door_students + case when p_kind = 'student' then p_delta else 0 end),
        updated_at = now()
    where event_id = v_event.id
    returning * into v_live;
    return jsonb_build_object('status', 'ok', 'door_cash', v_live.door_cash, 'door_free', v_live.door_free, 'door_students', v_live.door_students);
end;
$$;
grant execute on function public.comp_door_count(text, text, integer) to anon;
