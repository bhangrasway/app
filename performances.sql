-- ============================================================================
-- PERFORMANCES — run once in the Supabase SQL editor
-- (Project -> SQL Editor -> New query -> paste -> Run).
--
-- Powers the new "Performances" tab in admin.html and the public
-- phone-verified perform.html page:
--   * performances            — one row per "performance call" the admin opens.
--   * performance_signups     — who joined, their roster tier/team/dress color.
--   * performance_movements   — ordered choreography steps, optionally tied to
--                                a time range in the uploaded song.
--   * performance_positions   — each dancer's x/y stage position per movement.
--   * performance_attendance  — rehearsal (not class) attendance per session.
--
-- Access model: TIGHTER than the older tables in this app. students/
-- attendance/fees_paid run with RLS off (accepted long ago, before phone
-- privacy mattered as much); this feature stores names next to dress colors
-- and stage positions, so RLS stays ON here:
--   * authenticated (logged-in admin)  — full read/write on every table.
--   * anon (public perform.html)       — SELECT on `performances` only
--     (to show the open call's title/date). Everything else — joining,
--     the joined-count, and "my spot" — goes through phone-verified
--     security-definer RPCs, which bypass RLS internally but never expose
--     other members' names/positions in their return values.
-- ============================================================================

-- ===== 1. Tables ============================================================
create table if not exists public.performances (
    id              bigint generated by default as identity primary key,
    title           text not null,
    event_date      date,
    status          text not null default 'open' check (status in ('open', 'closed')),
    front_band_pct  numeric not null default 25,
    song_url        text,
    created_at      timestamptz not null default now()
);

create table if not exists public.performance_signups (
    id              bigint generated by default as identity primary key,
    performance_id  bigint not null references public.performances(id) on delete cascade,
    student_id      bigint not null references public.students(id),
    student_name    text not null,
    roster_status   text not null default 'beginner'
                        check (roster_status in ('advanced', 'intermediate', 'beginner', 'spare')),
    team            text check (team in ('A', 'B')),  -- null = unassigned / spare pool
    dress_color     text check (dress_color in ('red', 'green', 'purple', 'orange', 'sky_blue', 'royal_blue')),
    joined_at       timestamptz not null default now(),
    unique (performance_id, student_id)
);

create table if not exists public.performance_movements (
    id              bigint generated by default as identity primary key,
    performance_id  bigint not null references public.performances(id) on delete cascade,
    movement_order  integer not null,
    label           text,
    start_seconds   numeric,
    end_seconds     numeric,
    unique (performance_id, movement_order)
);

create table if not exists public.performance_positions (
    id           bigint generated by default as identity primary key,
    movement_id  bigint not null references public.performance_movements(id) on delete cascade,
    student_id   bigint not null references public.students(id),
    x            numeric not null default 50,
    y            numeric not null default 50,
    unique (movement_id, student_id)
);

create table if not exists public.performance_attendance (
    id              bigint generated by default as identity primary key,
    performance_id  bigint not null references public.performances(id) on delete cascade,
    student_id      bigint not null references public.students(id),
    session_date    date not null,
    present         boolean not null default false,
    unique (performance_id, student_id, session_date)
);

