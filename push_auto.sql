-- AUTOMATIC NOTIFICATIONS — run once in the Supabase SQL editor
-- (Project -> SQL Editor -> New query -> paste -> Run), AFTER
-- push_notifications.sql and admin_push.sql (it uses the same Vault secret
-- 'push_trigger_secret'). Safe to re-run.
--
-- BEFORE running: Dashboard -> Database -> Extensions -> enable "pg_cron".
--
--  * Class reminders: the evening before each batch's class day, at the time
--    set per batch, every student of that batch with notifications on gets a
--    catchy message (picked at random from the batch's list, or the default
--    list). Placeholders: {nome} {batch} {ora} {sede}.
--  * Birthday wishes: on the birthday (from the codice fiscale), at the set
--    time.
--  * Days off: a date in push_skip_dates (optionally only one location) = no
--    reminder for classes on that date.
--
-- Every 15 minutes pg_cron calls the Edge Function "send-push" with
-- { to: 'auto' }; the function sends what is due and writes push_auto_log so
-- nothing is sent twice. All set from admin.html -> Students -> «Auto notifications».
-- ============================================================================

-- The 15-minute timer (pg_cron) and outgoing calls (pg_net, already on from admin_push.sql).
create extension if not exists pg_cron;
create extension if not exists pg_net with schema extensions;

create table if not exists public.push_auto_settings (
    id int primary key default 1 check (id = 1),
    reminders_enabled boolean not null default false,
    default_messages jsonb not null default '[]'::jsonb,
    birthday_enabled boolean not null default false,
    birthday_time time not null default '09:00',
    birthday_messages jsonb not null default '[]'::jsonb,
    updated_at timestamptz not null default now()
);
insert into public.push_auto_settings (id) values (1) on conflict (id) do nothing;
-- The admin's own «Credit €0 or less» message (Send notification window).
alter table public.push_auto_settings add column if not exists low_credit_title text;
alter table public.push_auto_settings add column if not exists low_credit_body text;
-- «Sei in sala? Tocca qui»: at class time, to the batch's students not checked in yet.
alter table public.push_auto_settings add column if not exists checkin_enabled boolean not null default false;
alter table public.push_auto_settings add column if not exists checkin_offset_min int not null default 0;
alter table public.push_auto_settings add column if not exists checkin_messages jsonb not null default '[]'::jsonb;

-- One row per batch (missing row = reminders on, 19:00, default messages).
create table if not exists public.push_reminders (
    batch_id bigint primary key references public.batches(id) on delete cascade,
    enabled boolean not null default true,
    send_time time not null default '19:00',
    messages jsonb not null default '[]'::jsonb,
    updated_at timestamptz not null default now()
);

create table if not exists public.push_skip_dates (
    id bigint generated by default as identity primary key,
    skip_date date not null,
    location_id bigint references public.locations(id) on delete cascade, -- null = all locations
    note text,
    created_at timestamptz not null default now()
);

create table if not exists public.push_auto_log (
    kind text not null,          -- 'reminder' | 'birthday'
    ref text not null,           -- batch id / student id
    for_date date not null,      -- class date / birthday date
    sent int not null default 0,
    created_at timestamptz not null default now(),
    primary key (kind, ref, for_date)
);

alter table public.push_auto_settings enable row level security;
alter table public.push_reminders enable row level security;
alter table public.push_skip_dates enable row level security;
alter table public.push_auto_log enable row level security;
drop policy if exists "authenticated_all" on public.push_auto_settings;
create policy "authenticated_all" on public.push_auto_settings for all to authenticated using (true) with check (true);
drop policy if exists "authenticated_all" on public.push_reminders;
create policy "authenticated_all" on public.push_reminders for all to authenticated using (true) with check (true);
drop policy if exists "authenticated_all" on public.push_skip_dates;
create policy "authenticated_all" on public.push_skip_dates for all to authenticated using (true) with check (true);
drop policy if exists "authenticated_all" on public.push_auto_log;
create policy "authenticated_all" on public.push_auto_log for all to authenticated using (true) with check (true);
revoke all on public.push_auto_settings from anon;
revoke all on public.push_reminders from anon;
revoke all on public.push_skip_dates from anon;
revoke all on public.push_auto_log from anon;

