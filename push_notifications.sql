-- ============================================================================
-- STUDENT PUSH NOTIFICATIONS — run once in the Supabase SQL editor
-- (Project -> SQL Editor -> New query -> paste -> Run). Safe to re-run.
--
-- Students turn on notifications in member.html (installed on the home screen
-- on iPhone). Each phone/browser gives a "subscription" (endpoint + keys),
-- saved here for that student. The admin writes a message in admin.html and
-- the Edge Function "send-push" (supabase/functions/send-push) delivers it.
--
--   push_subscriptions  one row per (phone/browser, student). A parent's phone
--                       with two children has two rows, same endpoint; the
--                       sender sends each phone one copy per message.
--   push_messages       history of what was sent, to whom, how many reached.
--
-- Students never read these tables: they only call the two functions below
-- (the same phone + passcode check as every other member action).
-- ============================================================================

create table if not exists public.push_subscriptions (
    id bigint generated by default as identity primary key,
    student_id bigint not null references public.students(id) on delete cascade,
    endpoint text not null,
    p256dh text not null,
    auth text not null,
    user_agent text,
    created_at timestamptz not null default now(),
    last_seen_at timestamptz not null default now(),
    unique (endpoint, student_id)
);
create index if not exists push_subscriptions_student_idx on public.push_subscriptions (student_id);

create table if not exists public.push_messages (
    id bigint generated by default as identity primary key,
    title text not null,
    body text not null,
    target_label text,
    student_count int not null default 0,
    device_count int not null default 0,
    sent int not null default 0,
    failed int not null default 0,
    created_at timestamptz not null default now()
);

alter table public.push_subscriptions enable row level security;
alter table public.push_messages enable row level security;

drop policy if exists "authenticated_all" on public.push_subscriptions;
create policy "authenticated_all" on public.push_subscriptions for all to authenticated using (true) with check (true);
drop policy if exists "authenticated_all" on public.push_messages;
create policy "authenticated_all" on public.push_messages for all to authenticated using (true) with check (true);

revoke all on public.push_subscriptions from anon;
revoke all on public.push_messages from anon;

-- Member: save this phone's subscription for this student (after phone + passcode check).
create or replace function public.save_push_subscription_by_phone(
    p_student_id bigint,
    p_phone text,
    p_passcode text,
    p_endpoint text,
    p_p256dh text,
    p_auth text,
    p_user_agent text default null
)
returns text
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
    if not public._phone_matches_student(p_student_id, p_phone) then
        return 'bad_phone';
    end if;
    if not public._passcode_matches_student(p_student_id, p_passcode) then
        return 'bad_passcode';
    end if;
    if coalesce(p_endpoint, '') !~ '^https://' or length(p_endpoint) > 1000
       or coalesce(p_p256dh, '') = '' or coalesce(p_auth, '') = '' then
        return 'bad_subscription';
    end if;

    insert into public.push_subscriptions (student_id, endpoint, p256dh, auth, user_agent)
    values (p_student_id, p_endpoint, p_p256dh, p_auth, left(p_user_agent, 300))
    on conflict (endpoint, student_id) do update
        set p256dh = excluded.p256dh, auth = excluded.auth,
            user_agent = excluded.user_agent, last_seen_at = now();
    return 'saved';
end;
$$;

-- Member: "Turn off" on this phone. Only whoever holds the endpoint (a long
-- secret URL known to that browser) can remove it.
create or replace function public.remove_push_subscription(p_endpoint text)
returns text
language sql
security definer
set search_path = public, pg_temp
as $$
    delete from public.push_subscriptions where endpoint = p_endpoint;
    select 'removed';
$$;

revoke all on function public.save_push_subscription_by_phone(bigint, text, text, text, text, text, text) from public;
revoke all on function public.remove_push_subscription(text) from public;
grant execute on function public.save_push_subscription_by_phone(bigint, text, text, text, text, text, text) to anon, authenticated;
grant execute on function public.remove_push_subscription(text) to anon, authenticated;
