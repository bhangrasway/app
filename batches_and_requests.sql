-- ===== 1. Batches =====
-- students.batch keeps storing the batch NAME (unchanged column/pattern) —
-- editing a batch's day/time here never touches a student row.
create table if not exists public.batches (
    id bigint generated by default as identity primary key,
    name text not null unique,
    day text not null,                    -- 'Saturday' | 'Sunday'
    start_time text not null,             -- e.g. '1:30 PM'
    end_time text not null,               -- e.g. '3:30 PM'
    category text not null,               -- 'beginner' | 'intermediate' | 'advance'
    min_capacity int not null default 8,
    max_capacity int not null default 12,
    sort_order int not null default 0,
    active boolean not null default true
);

-- Same trust model as students/attendance (checkin_settings.sql): RLS off,
-- both the admin dashboard (authenticated) and member.html (anon) read this
-- table directly, and only admin.html exposes any write UI for it.
alter table public.batches disable row level security;

