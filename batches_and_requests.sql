-- ===== 2. Batch change requests =====
-- Mirrors checkin_requests (checkin_settings.sql) exactly, same trust model:
-- RLS off, member.html never writes this table directly (it only ever calls
-- request_batch_change_by_phone below), admin.html reads/writes it directly.
create table if not exists public.batch_change_requests (
    id bigint generated by default as identity primary key,
    student_id bigint not null,
    student_name text not null,
    current_batch text,
    requested_batch text not null,
    status text not null default 'pending', -- 'pending' | 'approved' | 'dismissed'
    requested_at timestamptz not null default now(),
    resolved_at timestamptz
);

alter table public.batch_change_requests disable row level security;

-- ===== 3. RPC: request a batch move (phone + optional passcode verified) ====
-- Returns: 'sent' | 'bad_phone' | 'bad_passcode' | 'unknown_batch'
create or replace function public.request_batch_change_by_phone(
    p_student_id bigint,
    p_phone text,
    p_requested_batch text,
    p_passcode text default null
)
returns text
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_name text;
    v_current_batch text;
begin
    if not public._phone_matches_student(p_student_id, p_phone) then
        return 'bad_phone';
    end if;

    if not public._passcode_matches_student(p_student_id, p_passcode) then
        return 'bad_passcode';
    end if;

    if not exists (select 1 from public.batches where name = p_requested_batch and active) then
        return 'unknown_batch';
    end if;

    select name, batch into v_name, v_current_batch from public.students where id = p_student_id;

    -- Replace any existing pending request instead of stacking duplicates.
    update public.batch_change_requests
    set status = 'dismissed', resolved_at = now()
    where student_id = p_student_id and status = 'pending';

    insert into public.batch_change_requests (student_id, student_name, current_batch, requested_batch)
    values (p_student_id, v_name, v_current_batch, p_requested_batch);

    return 'sent';
end;
$$;

grant execute on function public.request_batch_change_by_phone(bigint, text, text, text) to anon;
