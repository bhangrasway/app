-- ============================================================================
-- JOB INCOME (CU) + REDDITI CHECKLIST — run once in the Supabase SQL editor
-- (Project -> SQL Editor -> New query -> paste -> Run). Safe to re-run.
--
-- Tasse tab → «Job income (CU)» and «Redditi checklist» (jobincome.js).
--  job_sources        each job / tirocinio of a year, plus its CU (March)
--  job_payslips       the monthly buste paga of a source (PDF in tax-pdfs)
--  redditi_checklist  per income year: ticked checks + the ricevuta PDF.
--                     Kept apart from tax_years, whose row means «official
--                     figures entered».
-- Admin only, like every other money table.
-- ============================================================================

create table if not exists public.job_sources (
    id bigint generated by default as identity primary key,
    anno int not null,
    nome text not null,
    cf_piva text,
    tipo text not null default 'dipendente' check (tipo in ('dipendente', 'tirocinio', 'altro')),
    dal date,
    al date,
    note text,
    cu_pdf_path text,
    cu_reddito numeric,
    cu_ritenute numeric,
    cu_add_regionale numeric,
    cu_add_comunale numeric,
    cu_giorni int,
    cu_ricevuta date,
    created_at timestamptz not null default now(),
    deleted_at timestamptz
);

create table if not exists public.job_payslips (
    id bigint generated by default as identity primary key,
    source_id bigint not null references public.job_sources(id),
    mese date not null,               -- 1st of the month
    lordo numeric,
    imponibile numeric,
    irpef numeric,
    netto numeric,
    pdf_path text,
    created_at timestamptz not null default now(),
    deleted_at timestamptz
);
create unique index if not exists job_payslips_one_per_month
    on public.job_payslips (source_id, mese) where deleted_at is null;

create table if not exists public.redditi_checklist (
    anno int primary key,             -- income year (Redditi sent the year after)
    ticks jsonb not null default '{}'::jsonb,
    ricevuta_pdf_path text,
    updated_at timestamptz not null default now()
);

alter table public.job_sources       enable row level security;
alter table public.job_payslips      enable row level security;
alter table public.redditi_checklist enable row level security;

